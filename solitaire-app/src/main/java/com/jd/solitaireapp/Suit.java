package com.jd.solitaireapp;

/** The four playing-card suits; color is determined by {@link Card#isRed()}. */
public enum Suit {
    /** Black Clubs. */
    CLUBS,
    /** Red Diamonds. */
    DIAMONDS,
    /** Red Hearts. */
    HEARTS,
    /** Black Spades, used for all cards in one-suit Spider. */
    SPADES
}
